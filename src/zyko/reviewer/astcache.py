"""ذاكرة مشي AST — نتيجة ast.walk تُحسب مرة واحدة لكل شجرة حية.

لماذا؟ قبل هذا الملف كانت القواعد الـ38 تعيد المشي على الشجرة نفسها لكل
قاعدة (×38 لكل مقطع) — الأداء الحقيقي كان يتضخم مع حجم الملف رغم أن كل
مشي إفرادي خطي. المشي البحثي (BFS) في ast.walk حتمي بالكامل، فتخزين
نتيجته لكل شجرة يحفظ المخرجات **بايت-ببايت** (الترتيب نفسه، العقد نفسها)
مع تقليص التكلفة إلى مشي واحد لكل شجرة.

العقد:
- المفاتيح ضعيفة (WeakKeyDictionary) فتُفرَّغ تلقائيًا مع تحرير الشجرة —
  لا تسرّب ذاكرة ولا حالة عابرة للأشجار الميتة.
- بلا مؤقتات ولا عشوائية ولا إدخال خارجي: العقدة نفسها ⇒ القائمة نفسها
  بالترتيب نفسه — عقد الحتمية البايتية للمراجع تنطبق كما هي.
- ملاحظة: ast.AST لا يعرّف __slots__ فالإحالة الضعيفة ممكنة، والمقارنة
  بالإسناد (identity hash) هي الافتراض — لا حاجة لأي تغيير في العقد.
"""

from __future__ import annotations

import ast
from weakref import WeakKeyDictionary

_WALK_CACHE: "WeakKeyDictionary[ast.AST, list[ast.AST]]" = WeakKeyDictionary()


def walk(tree: ast.AST) -> list[ast.AST]:
    """جميع عقد الشجرة بترتيب ast.walk البحثي — محسوبة مرة واحدة لكل شجرة.

    المكافئ البايتي للنداء المباشر ``ast.walk(tree)`` مع الفرق الوحيد أن
    العائد قائمة (قابلة لإعادة التكرار) بدل مولّد يُستهلك مرة واحدة —
    وهو ترقية لا كسر: كل مستهلك كان يكرر المولد مرة واحدة فقط.
    """
    cached = _WALK_CACHE.get(tree)
    if cached is None:
        cached = list(ast.walk(tree))
        _WALK_CACHE[tree] = cached
    return cached
